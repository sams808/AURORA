def slug(text: str) -> str:
    """The heading anchor, the same rule as aurora.app.help.slug (copied: that module imports PySide6)."""
    s = text.strip().lower()
    s = re.sub(r"[^\w\- ]", "", s, flags=re.UNICODE)
    return s.replace(" ", "-")


@dataclass(frozen=True)
class Term:
    key: str                        # 'i0'
    term: str                       # 'I0 (beam intensity)': the GLOSSARY.md heading
    short: str                      # 'I0': the word on screen, used in 'What is I0?'
    plain: str                      # one or two sentences, ends with '.'
    why: str                        # why it matters to the user
    where: str                      # the AURORA page / control it relates to (names as on screen)
    section: str                    # a key of SECTIONS
    aliases: tuple[str, ...] = ()   # other spellings found on screen
    gloss: tuple[str, ...] = ()     # plain phrases that explain the token in running text (the jargon guard)
    advanced: bool = False          # the term names an Advanced-only control
    question: str = ""              # 'What is a saturated detector?' (default 'What is {short}?')
    detail: str = ""                # expert detail: '*In the files:* ...' in GLOSSARY.md
    report: str = ""                # its sentence in the report's 'How to read the figures'

    @property
    def anchor(self) -> str:
        return slug(self.term)

    @property
    def ask(self) -> str:
        return self.question or f"What is {self.short}?"


