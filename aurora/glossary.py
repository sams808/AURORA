"""One source of words: every term AURORA shows, in plain language.

    from aurora.glossary import term, find, what_is
    what_is("i0")          # 'What is I0? The intensity of the X-ray beam arriving at the sample, ...'
    find("Au mesh").key    # 'i0'

The table feeds Help > Glossary (aurora/resources/docs/GLOSSARY.md, generated by `python -m aurora.glossary --write`
and checked by `--check`), the 'What is ...?' lines of the tooltips (aurora.app.help_text.HELP_TERMS), the linked words
of the captions (aurora.app.widgets.TermLabel), the report's 'How to read the figures' (report_paragraph) and the
jargon guard of the tests (JARGON, unexplained). Plain Python, no Qt import, so aurora.core.report can read it.

Values quoted here are AURORA's own (checked against xraydb and the code): the F K edge 696.7 eV, F Ka 676.8 eV,
O Ka 524.9 eV, 10 eV per detector channel without a calibration (constants.UNCALIBRATED_EV_PER_CH), the Easy scaling
ranges -20..-5 / +15..+35 eV (mode.EASY_DEFAULTS), 200 bootstrap draws, a beam intensity below 20 % of its median
(qc.check_zone). No depth is given for the electron yield or the fluorescence, and no R-factor threshold: those would
be invented values.
"""
